/* ══════════════════════════════════════════════════════════════════════════
   🧩 THE MODULE SAVE SHELF — one save field for every module that comes after.

   THE PROBLEM IT SOLVES. node-city's `serialize()` is a single 100-line object
   literal in an 24,000-line file that three workflows edit in the same round.
   Every feature that wants to persist something has to reach into it, and
   every one of those edits is a merge conflict and a chance to drop a field —
   which is precisely the failure mode the file's own comments record three
   times ("dropping it is a silent loss", "that failure is silent: production
   runs, the panel shows zero, nobody can tell why").

   So this batch of work adds ONE field, `ext`, and a registry behind it.
   A module calls

       window.MythicCitySave.register('names', { save(), load(payload) });

   and it is persisted from then on. Streets, zones and transit lines can each
   take a slot without going near serialize() again.

   🔑 LOAD ORDER IS THE HARD PART, and it is handled here rather than by each
   caller. loadState() runs during boot; a module may mount before it, after
   it, or (on a 404) never. So `restore()` STASHES the whole payload, and
   `register()` replays the stash to a late arrival immediately. A module that
   never loads leaves its slice untouched in the stash, and `collect()` writes
   that untouched slice straight back out — so a save round-trip through a
   build where a module was missing does NOT erase that module's data. That is
   the same instinct as node-city's own erasure guard, applied one level down.
   ══════════════════════════════════════════════════════════════════════════ */

const EXT_V = 1;

export class SaveShelf {
  constructor() {
    this.providers = new Map();   // id -> { save, load }
    this.stash = {};              // last payload seen by restore(), by id
    this.restored = false;
  }

  register(id, provider) {
    if (!id || !provider || typeof provider.save !== 'function') return false;
    this.providers.set(String(id), provider);
    /* Replay: a module that mounted AFTER loadState still gets its data. */
    if (this.restored && typeof provider.load === 'function') {
      try { provider.load(this.stash[id]); } catch (e) { console.warn('[save-ext] load ' + id, e); }
    }
    return true;
  }

  /* Called from serialize(). Never throws — a module whose save() blows up
     costs itself its slice and nothing else, and the rest of the city still
     writes. Its PREVIOUS slice is preserved rather than dropped. */
  collect() {
    const out = { v: EXT_V };
    for (const id in this.stash) if (!this.providers.has(id)) out[id] = this.stash[id];
    for (const [id, p] of this.providers) {
      try {
        const v = p.save();
        if (v !== undefined) out[id] = v;
      } catch (e) {
        console.warn('[save-ext] save ' + id, e);
        if (this.stash[id] !== undefined) out[id] = this.stash[id];
      }
    }
    return out;
  }

  /* Called from loadState(). `obj` absent (every save written before this
     shipped) is a no-op that still marks the shelf restored, so a module
     registering later is told "there was nothing for you" rather than waiting
     forever for a payload that is never coming. */
  restore(obj) {
    this.restored = true;
    this.stash = (obj && typeof obj === 'object') ? obj : {};
    for (const [id, p] of this.providers) {
      if (typeof p.load !== 'function') continue;
      try { p.load(this.stash[id]); } catch (e) { console.warn('[save-ext] restore ' + id, e); }
    }
    return Object.keys(this.stash).filter((k) => k !== 'v');
  }

  /* ── the self-describing header ────────────────────────────────────────
     The user is wiring the cloud side themselves ("I will add all this when we
     are done here and ready for the hand over"), which means somebody who did
     not write this file has to be able to look at one payload and know what is
     in it, which version wrote it, and which optional parts are present. That
     is what this block is for, and it is generated by WALKING the payload
     rather than by listing keys by hand — so a field another workflow adds to
     serialize() next week is described automatically instead of silently
     missing from the manifest. ~200 bytes. See /src/naming/HANDOVER.md. */
  describe(payload) {
    const p = (payload && typeof payload === 'object') ? payload : {};
    let tiles = 0;
    try { tiles = Object.keys(p.tiles || {}).length; } catch (e) {}
    return {
      app: 'node-city',
      /* The city save's own schema number, read off the payload rather than
         duplicated here — one place to bump, and it stays right when someone
         else bumps it. */
      schema: p.v | 0,
      ext: EXT_V,
      wrote: Date.now(),
      build: (typeof window !== 'undefined' && window.NC_BUILD) || null,
      keys: Object.keys(p).sort(),
      modules: Object.keys(p.ext || {}).filter((k) => k !== 'v').sort(),
      tiles,
      doc: '/src/naming/HANDOVER.md',
    };
  }
}
